#!/usr/bin/env bash
set -euo pipefail

# Bootstrap a Flipper Zero FAP and configure it for Neovim development
# (clangd LSP + nvim-dap). See README.md.
#
#   setup.sh <appid>             create an architected project (default)
#   setup.sh --minimal <appid>   create a single-file runloop project
#   setup.sh                      configure an existing project (run from its root)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE_DIR="$SCRIPT_DIR/template"
UFBT_DIR="$HOME/.ufbt"

if ! command -v ufbt &>/dev/null; then
    echo "Error: ufbt not found in PATH. Install from https://github.com/flipperdevices/flipperzero-ufbt"
    exit 1
fi

# --- parse args ---
MINIMAL=0
APPID=""
for arg in "$@"; do
    case "$arg" in
        --minimal) MINIMAL=1 ;;
        -*) echo "Error: unknown flag '$arg'"; exit 1 ;;
        *) APPID="$arg" ;;
    esac
done

# sed -i differs between GNU (Linux) and BSD (macOS)
if sed --version >/dev/null 2>&1; then
    sed_inplace() { sed -i "$@"; }
else
    sed_inplace() { sed -i '' "$@"; }
fi

# Turn an appid into a display name: "my_cool_app" -> "My Cool App"
display_name() {
    echo "$1" | tr '_' ' ' | awk '{ for(i=1;i<=NF;i++) $i=toupper(substr($i,1,1)) substr($i,2) }1'
}

scaffold_arch() {
    local appid="$1"
    local name
    name="$(display_name "$appid")"

    echo "==> overlaying architected template"
    rm -f "$appid.c"                 # drop ufbt's default single-file stub
    cp -R "$TEMPLATE_DIR/." .        # our application.fam overwrites the generated one

    # Replace tokens in all source/manifest files
    find . -type f \( -name '*.c' -o -name '*.h' -o -name 'application.fam' \) \
        -not -path './.git/*' -print0 |
        while IFS= read -r -d '' f; do
            sed_inplace -e "s/__APPID__/$appid/g" -e "s/__APP_NAME__/$name/g" "$f"
        done
}

scaffold_minimal() {
    local appid="$1"
    echo "==> writing single-file runloop + UI template to $appid.c"
    cat > "$appid.c" << EOF
#include <furi.h>
#include <gui/gui.h>
#include <input/input.h>

/* generated by fbt from .png files in images folder */
#include <${appid}_icons.h>

static void draw_callback(Canvas* canvas, void* ctx) {
    UNUSED(ctx);
    canvas_clear(canvas);
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str(canvas, 2, 14, "Hello world");
    canvas_set_font(canvas, FontSecondary);
    canvas_draw_str(canvas, 2, 30, "Press Back to exit");
}

static void input_callback(InputEvent* event, void* ctx) {
    furi_message_queue_put((FuriMessageQueue*)ctx, event, FuriWaitForever);
}

int32_t ${appid}_app(void* p) {
    UNUSED(p);

    FuriMessageQueue* queue = furi_message_queue_alloc(8, sizeof(InputEvent));

    ViewPort* view_port = view_port_alloc();
    view_port_draw_callback_set(view_port, draw_callback, NULL);
    view_port_input_callback_set(view_port, input_callback, queue);

    Gui* gui = furi_record_open(RECORD_GUI);
    gui_add_view_port(gui, view_port, GuiLayerFullscreen);

    InputEvent event;
    bool running = true;
    while(running) {
        if(furi_message_queue_get(queue, &event, FuriWaitForever) == FuriStatusOk) {
            if(event.type == InputTypeShort && event.key == InputKeyBack) {
                running = false;
            }
        }
    }

    gui_remove_view_port(gui, view_port);
    view_port_free(view_port);
    furi_record_close(RECORD_GUI);
    furi_message_queue_free(queue);

    return 0;
}
EOF
}

# --- scaffold (new project) or require an existing one ---
if [ -n "$APPID" ]; then
    if [ -e "$APPID" ]; then
        echo "Error: '$APPID' already exists. Pick a different appid or remove it first."
        exit 1
    fi
    echo "==> creating new project '$APPID'"
    mkdir "$APPID"
    cd "$APPID"
    ufbt create "APPID=$APPID"

    if [ "$MINIMAL" -eq 1 ]; then
        scaffold_minimal "$APPID"
    else
        scaffold_arch "$APPID"
    fi
else
    if [ ! -f "application.fam" ]; then
        echo "Usage: setup.sh [--minimal] <appid>   # create + configure a new FAP project"
        echo "       setup.sh                        # configure existing project (run from its root)"
        exit 1
    fi
fi

echo "==> ufbt build (generates *_icons.h and other build-time headers)"
ufbt

echo "==> ufbt vscode_dist (generates .vscode/compile_commands.json)"
ufbt vscode_dist

echo "==> symlinking compile_commands.json"
ln -sf .vscode/compile_commands.json compile_commands.json

# vscode_dist reinstalls .gitignore, so add host-test artifacts here (after it).
# Only the architected template has host tests (tests/test_counter.c).
if [ -f tests/test_counter.c ] && [ -f .gitignore ] &&
    ! grep -q '^/test_counter$' .gitignore; then
    printf '\n# host unit-test artifacts\n/test_counter\n*.o\n' >> .gitignore
fi

# Detect native toolchain arch; prefer arm64-darwin on Apple Silicon
if [ -d "$UFBT_DIR/toolchain/arm64-darwin/arm-none-eabi/include" ]; then
    ARM_INCLUDE="$UFBT_DIR/toolchain/arm64-darwin/arm-none-eabi/include"
elif [ -d "$UFBT_DIR/toolchain/x86_64-darwin/arm-none-eabi/include" ]; then
    ARM_INCLUDE="$UFBT_DIR/toolchain/x86_64-darwin/arm-none-eabi/include"
else
    echo "Warning: arm-none-eabi/include not found under $UFBT_DIR/toolchain — .clangd isystem path left empty"
    ARM_INCLUDE=""
fi

echo "==> writing .clangd (toolchain: $ARM_INCLUDE)"
cat > .clangd << EOF
CompileFlags:
  Add:
    - --target=arm-none-eabi
$([ -n "$ARM_INCLUDE" ] && echo "    - -isystem$ARM_INCLUDE")
    - -Wno-unknown-warning-option
  Remove:
    - -mword-relocations
    - -mlong-calls
    - -mfloat-abi=*
    - -mfpu=*
    - -Wa,*
Diagnostics:
  UnusedIncludes: None
EOF

echo ""
echo "Done. cd $([ -n "$APPID" ] && echo "$APPID " || echo "")&& nvim . — clangd LSP and nvim-dap debugger are ready."
[ "$MINIMAL" -eq 0 ] && [ -n "$APPID" ] && echo "Run host domain tests with: make test"
